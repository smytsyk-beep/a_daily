"""Prompt templates для LLM-улучшения дайджеста (русская локаль)."""

from typing import List

# Длина в символах для подсказки модели
LENGTH_CHARS = {
    "short": "300–500",
    "medium": "600–900",
    "long": "1000–1500",
}

SYSTEM_PROMPT_RU = """Ты — астрологический копирайтер для AstroDaily.
Твоя задача: создать дружелюбный, практичный дайджест на основе готовых блоков.

Стиль:
- Тон: поддерживающий, но не "сиропный"
- Фокус: что это значит в жизни, что делать
- Без эзотерики и жёстких предсказаний
- Язык: русский, естественный

Ограничения:
- Не выдумывай факты — используй только смысл из присланных блоков
- Сохраняй практические советы и CTA из блоков
- Не добавляй новые астрологические утверждения"""


def build_digest_prompt_ru(
    atom_texts: List[str],
    length: str,
    interests: List[str],
) -> str:
    """
    Собирает user prompt для комбинирования атомов в один связный текст.

    atom_texts: список текстов из выбранных атомов (body/copy_short/copy_long).
    length: "short" | "medium" | "long"
    interests: темы пользователя для акцента (work, relationships, money, selfcare...).
    """
    char_range = LENGTH_CHARS.get(length, "600–900")
    interests_str = ", ".join(interests) if interests else "общие темы"
    blocks = "\n\n---\n\n".join(f"[Блок {i+1}]\n{t}" for i, t in enumerate(atom_texts))

    return f"""Ниже — несколько блоков контента для дневного астродайджеста.
Объедини их в один связный текст без повторов.

Целевая длина: {char_range} символов.
Акцент для читателя: {interests_str}.

Требования:
1. Один плавный текст (2–4 абзаца).
2. Главное астрособытие/тема дня — в начале.
3. Практический совет или вывод — в конце.
4. Не копируй блоки дословно — переформулируй связно.

Блоки:

{blocks}

Ответь только текстом дайджеста, без заголовка и подписи."""


def build_title_prompt_ru(body_preview: str, max_words: int = 6) -> str:
    """Промпт для генерации короткого заголовка по началу текста."""
    preview = body_preview[:400] if body_preview else ""
    return f"""По началу текста дайджеста придумай короткий заголовок (до {max_words} слов).
Только заголовок, без кавычек и точки.

Начало текста:
{preview}

Заголовок:"""
