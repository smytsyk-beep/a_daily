def main():
    print("=" * 80)
    print("SEED TRANSIT ATOMS RU — BATCH 2")
    print("=" * 80)
    print()

    with session_scope() as db:
        print(f"Adding {len(BATCH2_ATOMS)} Russian transit atoms (batch 2)...")
        print()

        for i, atom_data in enumerate(BATCH2_ATOMS, 1):
            atom = models.ContentAtom(
                locale=atom_data["locale"],
                trigger=atom_data["trigger"],
                topic_tag=atom_data["topic_tag"],
                persona_tags=atom_data["persona_tags"],
                body=atom_data["body"],
                copy_short=atom_data["copy_short"],
                copy_long=atom_data.get("copy_long") or atom_data["body"],
                cta=atom_data.get("cta"),
                style=atom_data.get("style", "neutral"),
            )
            db.add(atom)
            print(f"  {i}. Added: {atom_data['trigger']} ({atom_data['topic_tag']})")

        db.commit()
        print()
        print("Done.")

        ru_count = (
            db.query(models.ContentAtom)
            .filter(
                models.ContentAtom.locale == "ru",
                models.ContentAtom.trigger.isnot(None),
            )
            .count()
        )
        print(f"Total RU transit atoms in DB: {ru_count}")
    print("=" * 80)


if __name__ == "__main__":
    main()
