def main():
    print("=" * 80)
    print("SEED RU DAILY & SPECIAL ATOMS")
    print("=" * 80)

    with session_scope() as db:
        print(f"Adding {len(ATOMS)} atoms...")
        for i, a in enumerate(ATOMS, 1):
            atom = models.ContentAtom(
                locale=a["locale"],
                topic_tag=a["topic_tag"],
                trigger=a.get("trigger"),
                persona_tags=a["persona_tags"],
                body=a["body"],
                copy_short=a.get("copy_short") or a["body"][:300],
                copy_long=a.get("copy_long") or a["body"],
                cta=a.get("cta"),
                style=a.get("style", "neutral"),
            )
            db.add(atom)
            print(f"  {i}. {a['topic_tag']} (ru)")
        db.commit()
        print("Done.")
    print("=" * 80)


if __name__ == "__main__":
    main()
