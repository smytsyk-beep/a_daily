def main():
    print("=" * 80)
    print("SEED TRANSIT ATOMS RU — BATCH 3")
    print("=" * 80)
    with session_scope() as db:
        print(f"Adding {len(BATCH3_ATOMS)} atoms...")
        for i, a in enumerate(BATCH3_ATOMS, 1):
            atom = models.ContentAtom(
                locale=a["locale"],
                trigger=a["trigger"],
                topic_tag=a["topic_tag"],
                persona_tags=a["persona_tags"],
                body=a["body"],
                copy_short=a.get("copy_short") or a["body"],
                copy_long=a.get("copy_long") or a["body"],
                cta=a.get("cta"),
                style=a.get("style", "neutral"),
            )
            db.add(atom)
            print(f"  {i}. {a['trigger']}")
        db.commit()
        ru = db.query(models.ContentAtom).filter(
            models.ContentAtom.locale == "ru",
            models.ContentAtom.trigger.isnot(None),
        ).count()
        print(f"Total RU transit atoms: {ru}")
    print("=" * 80)


if __name__ == "__main__":
    main()
